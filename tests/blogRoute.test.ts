import { readFileSync } from 'node:fs';
import { describe, expect, it, vi } from 'vitest';
import type { AuthorEntry, BlogEntry, BlogLookup } from '../src/lib/blogPost';
import { loadBlogPost, normalizeBlogSlug } from '../src/lib/blogPost';

const authorReference = { collection: 'authors' as const, id: 'alex-johnson' };

const post = {
  id: 'first-post',
  collection: 'blog',
  data: {
    title: 'First post',
    description: 'Lorem ipsum dolor sit amet',
    pubDate: new Date('2022-07-08T00:00:00.000Z'),
    heroImage: { src: '/hero.jpg', width: 1020, height: 510, format: 'jpg' },
    author: authorReference,
  },
} as unknown as BlogEntry;

const author = {
  id: 'alex-johnson',
  collection: 'authors',
  data: {
    name: 'Alex Johnson',
    bio: 'Writes about web development.',
    socialLinks: [],
  },
} as unknown as AuthorEntry;

const Content = (() => null) as unknown as Awaited<
  ReturnType<BlogLookup['render']>
>['Content'];

function createLookup(overrides: Partial<BlogLookup> = {}): BlogLookup {
  return {
    getBlogEntry: vi.fn(async (id: string) =>
      id === post.id ? post : undefined,
    ),
    getAuthorEntry: vi.fn(async () => author),
    render: vi.fn(async () => ({
      Content,
      headings: [],
      remarkPluginFrontmatter: {},
    })),
    ...overrides,
  };
}

describe('normalizeBlogSlug', () => {
  it('accepts ids generated by the glob loader', () => {
    expect(normalizeBlogSlug('first-post')).toBe('first-post');
    expect(normalizeBlogSlug('markdown-style-guide')).toBe(
      'markdown-style-guide',
    );
    expect(normalizeBlogSlug('using-mdx')).toBe('using-mdx');
    expect(normalizeBlogSlug('  second-post  ')).toBe('second-post');
  });

  it('keeps the directory segments of an entry in a subdirectory', () => {
    // The glob loader strips the extension but keeps subdirectories, and the
    // catch-all route passes the whole path, so a nested post must not 404.
    expect(normalizeBlogSlug('guides/first-post')).toBe('guides/first-post');
    expect(normalizeBlogSlug('blog/first-post')).toBe('blog/first-post');
  });

  it('rejects missing, empty and path-like parameters', () => {
    const rejected = [
      undefined,
      '',
      '   ',
      '/first-post',
      'first-post/',
      'guides//first-post',
      'guides/../first-post',
      'guides/first-post/',
      '../first-post',
      'first..post',
      'first post',
      'first%2Fpost',
      'x'.repeat(129),
    ];

    for (const value of rejected) {
      expect(normalizeBlogSlug(value)).toBeNull();
    }
  });
});

describe('loadBlogPost', () => {
  it('loads the post, author and rendered content for a valid slug', async () => {
    const lookup = createLookup();

    const result = await loadBlogPost('first-post', lookup);

    expect(result).not.toBeNull();
    expect(result?.post).toBe(post);
    expect(result?.author).toBe(author);
    expect(result?.Content).toBe(Content);
    expect(lookup.getBlogEntry).toHaveBeenCalledWith('first-post');
    expect(lookup.getAuthorEntry).toHaveBeenCalledWith(authorReference);
    expect(lookup.render).toHaveBeenCalledWith(post);
  });

  it('keeps the entry metadata intact for the layout', async () => {
    const lookup = createLookup();

    const result = await loadBlogPost('first-post', lookup);

    expect(result?.post.data).toMatchObject({
      title: 'First post',
      description: 'Lorem ipsum dolor sit amet',
      pubDate: new Date('2022-07-08T00:00:00.000Z'),
    });
    // The reference itself must survive; the page resolves it to the author
    // data. Replacing it here would change what the layout receives.
    expect(result?.post.data.author).toBe(authorReference);
  });

  it('returns null for a post that does not exist without rendering it', async () => {
    const getAuthorEntry = vi.fn(async () => author);
    const render = vi.fn();
    const lookup = createLookup({
      getBlogEntry: vi.fn(async () => undefined),
      getAuthorEntry,
      render,
    });

    await expect(loadBlogPost('missing-post', lookup)).resolves.toBeNull();
    expect(getAuthorEntry).not.toHaveBeenCalled();
    expect(render).not.toHaveBeenCalled();
  });

  it('forwards a nested entry id to the content lookup', async () => {
    const nestedPost = { ...post, id: 'guides/first-post' } as BlogEntry;
    const lookup = createLookup({
      getBlogEntry: vi.fn(async (id: string) =>
        id === 'guides/first-post' ? nestedPost : undefined,
      ),
    });

    const result = await loadBlogPost('guides/first-post', lookup);

    expect(result?.post).toBe(nestedPost);
    expect(lookup.getBlogEntry).toHaveBeenCalledWith('guides/first-post');
  });

  it('returns null for a malformed slug without querying content', async () => {
    const lookup = createLookup();

    await expect(loadBlogPost('../first-post', lookup)).resolves.toBeNull();
    expect(lookup.getBlogEntry).not.toHaveBeenCalled();
  });

  it('still renders a post whose author reference cannot be resolved', async () => {
    const lookup = createLookup({
      getAuthorEntry: vi.fn(async () => undefined),
    });

    const result = await loadBlogPost('first-post', lookup);

    expect(result).not.toBeNull();
    expect(result?.author).toBeUndefined();
    expect(result?.Content).toBe(Content);
  });
});

describe('blog route wiring', () => {
  const routeSource = readFileSync(
    new URL('../src/pages/blog/[...slug].astro', import.meta.url),
    'utf8',
  );

  it('resolves the entry from the route parameter instead of build-time props', () => {
    // Under `output: 'server'` the route is rendered on demand. `getStaticPaths`
    // never supplies props there, which is what returned 500 for every post.
    expect(routeSource).toContain('Astro.params.slug');
    expect(routeSource).not.toContain('Astro.props');
    expect(routeSource).not.toContain('getStaticPaths');
  });
});
